describe("languages", () => {
  test("supports every documented language code and alias locally", () => {
    expect(supportedCodes).toHaveLength(138);

    for (const code of supportedCodes) {
      expect(isSupported(code)).toBe(true);
      expect(getCode(code.toUpperCase())).toBe(code);
    }
  });

  test.each([
    ["English", "en"],
    ["Chinese (Simplified)", "zh"],
    ["Chinese (Traditional)", "zh-tw"],
    ["Haitian Creole", "ht"],
    ["Sepedi", "nso"],
    ["Turkmen", "tk"],
  ])("resolves language name %s", (name, code) => {
    expect(isSupported(name)).toBe(true);
    expect(getCode(name)).toBe(code);
  });

  test.each(["", "JavaScript", "undefined", "null"])(
    "rejects unsupported language %j",
    (language) => {
      expect(isSupported(language)).toBe(false);
      expect(getCode(language)).toBe("UNSUPPORTED");
    }
  );
});
